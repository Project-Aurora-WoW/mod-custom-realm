local spellIndex = {}   -- [spellID] = { classIdx, specIdx, spellIdx }
local glyphIndex = {}   -- [glyphID] = { classIdx, specIdx, glyphIdx, isMajor, level }

do
    for ci, cname in ipairs(CLASS_NAMES) do
        for si, spec in ipairs(SPELLS[cname]) do
            for pi, spell in ipairs(spec) do
                local ids, lvls = spell[1], spell[2]
                for ri, sid in ipairs(ids) do
                    if not spellIndex[sid] then
                        spellIndex[sid] = { classIdx = ci, specIdx = si, spellIdx = pi, rank = ri, ranks = #ids, ids = ids, levels = lvls }
                    end
                end
            end
        end
    end
    for ci, cname in ipairs(CLASS_NAMES) do
        for si, spec in ipairs(GLYPHS[cname]) do
            for gi, g in ipairs(spec) do
                if g[1] and g[1] ~= 0 then
                    glyphIndex[g[1]] = { classIdx = ci, specIdx = si, glyphIdx = gi, isMajor = (g[3] == 1), level = g[2] }
                end
            end
        end
    end
end

