    return math.floor(player:GetLevel() * CFG.spell_points_rate)
end
local function TotalGlyphMajor(player)
    return math.floor(((player:GetLevel() + 17.5) / 32.5) * CFG.glyph_major_rate)
end
local function TotalGlyphMinor(player)
    return math.floor(((player:GetLevel() + 12.5) / 27.5) * CFG.glyph_minor_rate)
end

-- ============================================================
-- ДАННЫЕ ИГРОКА (per-guid)
-- Полей: spells = { [spellID] = rank }, glyphs = { [glyphID] = true }
-- Потраченные очки считаем от текущего списка (ранг спелла = 1 очко).
-- ============================================================
local playerData = {}     -- [guid] = { spells = {...}, glyphs = {...} }

local function AllocSpellPoints(data)
    local sum = 0
    for _ in pairs(data.spells or {}) do sum = sum + 1 end
    return sum
end
local function AllocGlyphMajor(data)
    local sum = 0
    for gid in pairs(data.glyphs or {}) do
        local g = glyphIndex[gid]
        if g and g.isMajor then sum = sum + 1 end
    end
    return sum
end
local function AllocGlyphMinor(data)
    local sum = 0
    for gid in pairs(data.glyphs or {}) do
        local g = glyphIndex[gid]
        if g and not g.isMajor then sum = sum + 1 end
    end
    return sum
end

-- ============================================================
-- БД (character_classless, acore_characters; DDL — миграция 0025)
-- ============================================================
local function DBLoad(guid)
    local data = { spells = {}, glyphs = {}, talents = {}, hero = 0 }
    local ok, q = pcall(CharDBQuery, "SELECT spells, glyphs, talents, hero FROM character_classless WHERE guid = " .. guid)
    if ok and q then
        local spellsCSV = q:GetString(0)
        local glyphsCSV = q:GetString(1)
        local talentsCSV = q:GetString(2)
        data.hero = q:GetUInt32(3) or 0
        for sid in string.gmatch(spellsCSV or "", "([^,]+)") do
            local id = tonumber(sid)
            if id then data.spells[id] = true end
        end
        for gid in string.gmatch(glyphsCSV or "", "([^,]+)") do
            local id = tonumber(gid)
            if id then data.glyphs[id] = true end
        end
        for talentRec in string.gmatch(talentsCSV or "", "([^;]+)") do
            local sid, tid, rk = talentRec:match("^(%d+)|(%d+)|(%d+)$")
            if sid and tid and rk then
                data.talents[tonumber(sid)] = { talentID = tonumber(tid), rank = tonumber(rk) }
            end
        end
    else
        return nil   -- таблицы нет (миграция не применена) — система выключена
    end
    return data
end

local function DBSave(guid, data)
    local spellsCSV, glyphsCSV, talentsCSV = "", "", ""
    local first = true
    for sid in pairs(data.spells or {}) do
        if not first then spellsCSV = spellsCSV .. "," end
        spellsCSV = spellsCSV .. sid
        first = false
    end
    -- пересчитываем ранг (храним только «активно изучен»; ранг выводится от уровня)
    first = true
    for gid in pairs(data.glyphs or {}) do
        if not first then glyphsCSV = glyphsCSV .. "," end
        glyphsCSV = glyphsCSV .. gid
        first = false
    end
    first = true
    for sid, t in pairs(data.talents or {}) do
        if not first then talentsCSV = talentsCSV .. ";" end
        talentsCSV = talentsCSV .. sid .. "|" .. t.talentID .. "|" .. t.rank
        first = false
    end
    pcall(CharDBExecute,
        "REPLACE INTO character_classless (guid, spells, glyphs, talents, hero) VALUES (" .. guid ..
        ", '" .. spellsCSV .. "', '" .. glyphsCSV .. "', '" .. talentsCSV .. "', " .. (data.hero or 0) .. ")")
end

