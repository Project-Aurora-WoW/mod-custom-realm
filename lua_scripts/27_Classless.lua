local function OnChat(event, player, msg, lang, typ)
    if not msg or msg == "" then return end
    -- Команды с точкой приходят через строку чата; фильтр по префиксу
    local lower = msg:lower()
    if lower:sub(1, #CFG.command) ~= CFG.command then return end

    local args = {}
    for w in (msg:sub(#CFG.command + 1) or ""):gmatch("%S+") do args[#args + 1] = w end

    local cmd = args[1] and args[1]:lower() or "help"

    if cmd == "help" then
        SendHelp(player)
    elseif cmd == "status" then
        SendStatus(player)
    elseif cmd == "list" then
        local data = playerData[player:GetGUIDLow()]
        if not data then
            player:SendBroadcastMessage(TAG .. " система Classless отключена.")
            return
        end
        local n = 0
        for sid in pairs(data.spells or {}) do
            player:SendBroadcastMessage("  спелл " .. sid)
            n = n + 1
        end
        for gid in pairs(data.glyphs or {}) do
            player:SendBroadcastMessage("  глиф " .. gid)
            n = n + 1
        end
        for sid, t in pairs(data.talents or {}) do
            player:SendBroadcastMessage("  талант " .. t.talentID .. " (ранг " .. t.rank .. ")")
            n = n + 1
        end
        if n == 0 then player:SendBroadcastMessage(TAG .. " ничего не изучено.") end
    elseif cmd == "learn" or cmd == "unlearn" then
        local kind = args[2] and args[2]:lower() or ""
        local rawID = args[3] or args[2]
        -- Синтаксис: learn/unlearn <spell|glyph|talent> <id> [rank]
        local id = tonumber(rawID)
        if not id then
            player:SendBroadcastMessage(TAG .. " укажи тип (spell/glyph/talent) и ID.")
            return
        end
        local rank = tonumber(args[4] or "1")
        local err
        if kind == "talent" then
            if cmd == "learn" then
                err = LearnTalent(player, id, rank)
            else
                err = UnlearnTalent(player, id)
            end
        elseif kind == "glyph" then
            if cmd == "learn" then
                err = LearnGlyph(player, id)
            else
                err = UnlearnGlyph(player, id)
            end
        else -- по умолчанию (как раньше): spell (или glyph, если это глиф)
            if cmd == "learn" then
                if spellIndex[id] then
                    err = LearnSpell(player, id)
                else
                    err = LearnGlyph(player, id)
                end
            else
                if spellIndex[id] then
                    err = UnlearnSpell(player, id)
                else
                    err = UnlearnGlyph(player, id)
                end
            end
        end
        if err then player:SendBroadcastMessage(TAG .. " " .. err) end
    elseif cmd == "hero" then
        local err = ToggleHero(player)
        if err then player:SendBroadcastMessage(TAG .. " " .. err) end
    elseif cmd == "reset" then
        local guid = player:GetGUIDLow()
        local data = playerData[guid]
        if not data then
            player:SendBroadcastMessage(TAG .. " система Classless отключена.")
            return
        end
        if not CanReset(data) then
            player:SendBroadcastMessage(TAG .. " Нечего сбрасывать — чужие умения не изучены.")
            return
        end
        local cost = CFG.reset_costs[1]
        if player:GetCoinage() < cost then
            player:SendBroadcastMessage(TAG .. " Недостаточно золота (нужно " .. Currency(cost) .. ").")
            return
        end
        player:ModifyMoney(-cost)
        DoReset(player, data)
        DBSave(guid, data)
        player:SendBroadcastMessage(TAG .. " " .. VOID .. "Все чужие умения забыты за " .. Currency(cost) .. ".|r")
    else
        SendHelp(player)
    end
end

