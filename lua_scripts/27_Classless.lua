local function GetSpellRankForLevel(spellRef, level)
    local r = 0
    for i = 1, spellRef.ranks do
        if level >= spellRef.levels[i] then r = i else break end
    end
    return r
end

local function IsOwnClassSpell(player, classIdx)
    -- Класс игрока в терминах CLASS_NAMES (индекс): 1-10 как класс персонажа
    -- (11 = пет). Класс персонажа: 1 Воин,2 Паладин,3 Охотник,4 Разбойник,
    -- 5 Жрец,6 DK,7 Шаман,8 Маг,9 Чернокнижник,11 Друид.
    local pc = player:GetClass()
    local mapIdx = { [1]=10, [2]=5, [3]=3, [4]=7, [5]=6, [6]=1, [7]=8, [8]=4, [9]=9, [11]=2 }
    return (mapIdx[pc] == classIdx)
end

-- Фактические ID одного «семейства» (class/spec/spell) — один спелл с рангами.
local function SameSpell(a, b)
    return (a.classIdx == b.classIdx and a.specIdx == b.specIdx and a.spellIdx == b.spellIdx)
end
-- Найти изученный фактический ID спелла, относящийся к spellRef.
local function FindLearnedSpellID(data, spellRef)
    for k in pairs(data.spells or {}) do
        local r = spellIndex[k]
        if r and SameSpell(r, spellRef) then return k end
    end
    return nil
end

local function LearnSpell(player, spellID)
    local guid = player:GetGUIDLow()
    local data = playerData[guid]
    if not data then return "система недоступна (миграция 0025 не применена)" end

    local sr = spellIndex[spellID]
    if not sr then return "спелл " .. spellID .. " не найден в реестре Classless" end

    -- «Чужой» класс
    if IsOwnClassSpell(player, sr.classIdx) then
        return "это спелл твоего класса — изучать через тренера"
    end

    -- Потраченные очки
    if AllocSpellPoints(data) >= TotalSpellPoints(player) then
        return "не хватает очков спеллов (доступно: " .. (TotalSpellPoints(player) - AllocSpellPoints(data)) .. ")"
    end

    -- Уже изучен (любой ранг этого семейства) — ранк подтягиваем без доп. траты
    local learned = FindLearnedSpellID(data, sr)
    if learned then
        player:SendBroadcastMessage(TAG .. " " .. VOID .. "Умение уже изучено, ранг обновлён.|r")
        return nil
    end

    local rank = GetSpellRankForLevel(sr, player:GetLevel())
    if rank == 0 then return "уровень слишком низок для этого умения (" .. sr.levels[1] .. "+)" end

    local spellLearnedID = sr.ids[rank]
    player:LearnSpell(spellLearnedID)
    data.spells[spellLearnedID] = true
    DBSave(guid, data)
    player:SendBroadcastMessage(TAG .. " " .. VOID .. "Обучено чужое умение " .. spellLearnedID .. "|r")
    return nil
end

local function UnlearnSpell(player, spellID)
    local guid = player:GetGUIDLow()
    local data = playerData[guid]
    if not data then return "система недоступна" end
    local sr = spellIndex[spellID]
    if not sr then return "спелл " .. spellID .. " не найден в реестре" end
    local learned = FindLearnedSpellID(data, sr)
    if not learned then return "умение не изучено" end
    player:RemoveSpell(learned, 255, false)
    data.spells[learned] = nil
    DBSave(guid, data)
    player:SendBroadcastMessage(TAG .. " " .. VOID .. "Забыто чужое умение " .. learned .. "|r")
    return nil
end

local function LearnGlyph(player, glyphID)
    local guid = player:GetGUIDLow()
    local data = playerData[guid]
    if not data then return "система недоступна" end
    local g = glyphIndex[glyphID]
    if not g then return "глиф " .. glyphID .. " не найден в реестре" end
    if IsOwnClassSpell(player, g.classIdx) then
        return "это глиф твоего класса"
    end
    if g.level > player:GetLevel() then
        return "глиф требует уровень " .. g.level
    end
    if data.glyphs[glyphID] then return "глиф уже установлен" end
    -- слоты
    if g.isMajor and AllocGlyphMajor(data) >= TotalGlyphMajor(player) then
        return "нет свободных слотов больших глифов"
    end
    if not g.isMajor and AllocGlyphMinor(data) >= TotalGlyphMinor(player) then
        return "нет свободных слотов малых глифов"
    end
    player:LearnSpell(glyphID)
    data.glyphs[glyphID] = true
    DBSave(guid, data)
    player:SendBroadcastMessage(TAG .. " " .. VOID .. "Установлен чужой глиф " .. glyphID .. "|r")
    return nil
end

local function UnlearnGlyph(player, glyphID)
    local guid = player:GetGUIDLow()
    local data = playerData[guid]
    if not data then return "система недоступна" end
    local g = glyphIndex[glyphID]
    if not g then return "глиф " .. glyphID .. " не найден в реестре" end
    if not data.glyphs[glyphID] then return "глиф не установлен" end
    player:RemoveSpell(glyphID, 255, false)
    data.glyphs[glyphID] = nil
    DBSave(guid, data)
    player:SendBroadcastMessage(TAG .. " " .. VOID .. "Снят чужой глиф " .. glyphID .. "|r")
    return nil
end

-- ============================================================
-- ТАЛАНТЫ (Classless «полная версия», Фаза 3; миграция 0030)
-- Очки талантов Classless — отдельный пул (свой, не спеллов):
-- дают возможность учить ЧУЖИЕ таланты как собственные.
-- data.talents = { [talentSpellID] = { talentID = int, rank = int } }
-- Формат хранения в БД (колонка talents): 'talentSpellID|talentID|rank;'
--
-- talentIndex строится из БД ядра (tabel talent_dbc + talenttab_dbc,
-- acore_world): [talentID] = { spellIDs = {ранк=спелл}, tabID, classIdx }
-- это «честные» таланты 3.3.5a всех классов.
-- ============================================================
local talentIndex = {}   -- [talentID] = { spellIDs={}, tabID, classIdx, maxRank }

-- convert ChrClasses index (1=Воин..6=DK..11=Друид) в индекс CLASS_NAMES
-- (как использует IsOwnClassSpell): [chrClass] = classNamesIdx
local CHR_TO_CLASSNAMES = {
    [1] = 10,  -- Воин   -> CLASS_NAMES[10]
    [2] = 5,   -- Паладин -> CLASS_NAMES[5]
    [3] = 3,   -- Охотник -> CLASS_NAMES[3]
    [4] = 7,   -- Разбойник -> CLASS_NAMES[7]
    [5] = 6,   -- Жрец   -> CLASS_NAMES[6]
    [6] = 1,   -- DK     -> CLASS_NAMES[1]
    [7] = 8,   -- Шаман  -> CLASS_NAMES[8]
    [8] = 4,   -- Маг    -> CLASS_NAMES[4]
    [9] = 9,   -- Чернокнижник -> CLASS_NAMES[9]
    [11] = 2,  -- Друид  -> CLASS_NAMES[2]
}

local function LoadTalentIndex()
    talentIndex = {}
    -- talent_dbc: ID, TabID, TierID, ColumnIndex, SpellRank_0..4
    local tq = WorldDBQuery("SELECT ID, TabID, TierID, ColumnIndex, SpellRank_0, SpellRank_1, SpellRank_2, SpellRank_3, SpellRank_4 FROM talent_dbc")
    -- talenttab_dbc: ID, ..., RaceMask, ClassMask (индекс колонок зависит от схемы)
    local classes = {}   -- [tabID] = classNamesIdx
    local cq = WorldDBQuery("SELECT ID, ClassMask FROM talenttab_dbc")
    if cq then
        repeat
            -- ClassMask — битовая маска ChrClasses; класс = позиция первого
            -- установленного бита (1=Воин..11=Друид). Без битовых операторов
            -- (Lua 5.1 / ALE): ищем по целочисленному делению на 2.
            local cm = cq:GetUInt32(1)
            local chrClass = 1
            local rest = math.floor(cm)
            while rest > 0 and (rest % 2) == 0 do
                rest = math.floor(rest / 2)
                chrClass = chrClass + 1
            end
            if (rest % 2) == 1 and chrClass <= 11 then
                classes[cq:GetUInt32(0)] = CHR_TO_CLASSNAMES[chrClass] or 0
            end
        until not cq:NextRow()
    end
    -- MapTab (порядок табов внутри класса) → specIdx: talenttab_dbc не хранит
    -- порядка; используем TabID как specIdx (1..3 для стандартных классов).
    if tq then
        repeat
            local id = tq:GetUInt32(0)
            local tab = tq:GetUInt32(1)
            local tier = tq:GetUInt32(2)
            local col = tq:GetUInt32(3)
            local spellIDs = {}
            local maxRank = 0
            for r = 0, 4 do
                local sid = tq:GetUInt32(4 + r)
                if sid ~= 0 then
                    spellIDs[r + 1] = sid
                    maxRank = r + 1
                end
            end
            if maxRank > 0 then
                talentIndex[id] = {
                    spellIDs = spellIDs,
                    tabID = tab,
                    tier = tier,
                    col = col,
                    classIdx = classes[tab] or 0,
                    maxRank = maxRank,
                }
            end
        until not tq:NextRow()
    end
end
LoadTalentIndex()

local function TotalTalentPoints(player)
    -- 1 очко таланта Classless за каждый уровень, начиная с мин. уровня
    -- (настраивается в CFG). По умолчанию как у спеллов: уровень.
    return math.floor(player:GetLevel() * (CFG.talent_points_rate or 0))
end

local function AllocTalentPoints(data)
    local sum = 0
    for _, t in pairs(data.talents or {}) do sum = sum + (t.rank or 0) end
    return sum
end

-- Найти изученный талант в data по talentID
local function FindLearnedTalent(data, talentID)
    for id, t in pairs(data.talents or {}) do
        if t.talentID == talentID then return id, t end
    end
    return nil
end

